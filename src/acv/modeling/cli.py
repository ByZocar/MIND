"""CLI: `python -m acv.modeling.cli train` and `evaluate`.

Pipeline:
    train:
        - Load features_v1.parquet and split into train/test.
        - Run CV (StratifiedGroupKFold) on EVERY pipeline in
          `PIPELINES`, capture OOF metrics.
        - Persist `reports/model_card.md`, `reports/model_selection.csv`
          and the OOF prediction parquet.
    evaluate (champion):
        - Refit champion on ALL train data.
        - Evaluate on test set with the threshold tuned in CV.
        - Bootstrap CI at patient level (1000 resamples).
        - Persist `models/champion.pkl`, extends model_card.md.

The "champion" is selected by max OOF sensitivity (with specificity
>= min) and tie-broken by AUROC. The decision is logged in agent.md.
"""
