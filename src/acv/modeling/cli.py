def _pretty_table(results: list[CVResult]) -> Table:
    t = Table(title="CV Results (OOF on train)")
    t.add_column("Model")
    t.add_column("Thr", justify="right")
    t.add_column("Sens", justify="right")
    t.add_column("Sens 95% CI", justify="right")
    t.add_column("Spec", justify="right")
    t.add_column("AUROC", justify="right")
    t.add_column("AUROC 95% CI", justify="right")
    t.add_column("AUPRC", justify="right")
    t.add_column("Brier", justify="right")
    for r in results:
        m = r.metrics
        t.add_row(
            r.name,
            f"{r.threshold:.3f}",
            f"{m.sensitivity:.3f}",
            f"[{r.sens_ci[1]:.2f}, {r.sens_ci[2]:.2f}]",
            f"{m.specificity:.3f}",
            f"{m.auroc:.3f}",
            f"[{r.auroc_ci[1]:.2f}, {r.auroc_ci[2]:.2f}]",
            f"{m.auprc:.3f}",
            f"{m.brier:.3f}",
        )
    return t


def _save_oof(results: list[CVResult], path: Path) -> None:
    frames = []
    for r in results:
        df = pd.DataFrame(
            {
                "model": r.name,
                "patient_sk": r.oof_groups,
                "y_true": r.oof_true,
                "y_prob": r.oof_proba,
            }
        )
        frames.append(df)
    pd.concat(frames, ignore_index=True).to_parquet(path, index=False)


def _save_selection_csv(results: list[CVResult], path: Path) -> None:
    rows = []
    for r in results:
        row = {"model": r.name, **r.metrics.as_row(),
               "sens_ci_lo": r.sens_ci[1], "sens_ci_hi": r.sens_ci[2],
               "auroc_ci_lo": r.auroc_ci[1], "auroc_ci_hi": r.auroc_ci[2]}
        rows.append(row)
    pd.DataFrame(rows).sort_values("sensitivity", ascending=False).to_csv(path, index=False)


def _pick_champion(results: list[CVResult]) -> CVResult:
    eligible = [r for r in results if r.metrics.specificity >= settings.min_specificity]
    pool = eligible or results
    # max sensitivity; tie-break by AUROC
    return max(pool, key=lambda r: (r.metrics.sensitivity, r.metrics.auroc))


