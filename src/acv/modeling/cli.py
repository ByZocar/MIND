def cmd_train_slice(args: argparse.Namespace) -> None:
    """Slice-level CV across all candidate models + aggregator strategies."""
    t0 = time.time()
    console.print("[cyan]==> Loading slice-level data[/]")
    split = make_slice_split()
    console.print(
        f"   train: {len(split.X_train)} slices / {split.n_train_patients} patients | "
        f"test: {len(split.X_test)} slices / {split.n_test_patients} patients | "
        f"features: {len(split.feature_names)}"
    )

    # Subset of pipelines worth running on slice grain: skip clinical-only
    # (which by definition is constant per patient) and baseline_majority
    # (already trivial).
    candidates = {n: f for n, f in PIPELINES.items()
                  if n not in {"baseline_majority", "baseline_clinical_logreg"}}
    aggregators = args.aggregators.split(",") if args.aggregators else list(AGGREGATORS.keys())

    results: list[SliceCVResult] = []
    for name, factory in candidates.items():
        console.print(f"[cyan]==> Slice CV {name}  (k={args.k})[/]")
        # Compute slice-level OOF ONCE per (model, k), then reuse across all
        # aggregators. This makes the aggregator sweep nearly free.
        oof = _slice_oof(
            factory, split.X_train, split.y_train, split.groups_train,
            n_splits=5, seed=settings.random_seed, k=args.k,
        )
        for agg in aggregators:
            r = run_slice_cv(
                name, factory,
                split.X_train, split.y_train,
                split.groups_train, split.slice_weights_train,
                aggregator=agg, seed=settings.random_seed,
                bootstrap_n=args.bootstrap, k=args.k,
                calibrate=args.calibrate,
                oof_slice_precomputed=oof,
            )
            results.append(r)
            m = r.metrics
            console.print(
                f"   agg={agg:14s}  sens={m.sensitivity:.3f}  spec={m.specificity:.3f}  "
                f"auroc={m.auroc:.3f}  thr={r.threshold:.3f}"
            )

    console.print(_pretty_slice_table(results))

    # Select champion: max sensitivity s.t. spec >= min; tie-break by AUROC.
    eligible = [r for r in results if r.metrics.specificity >= settings.min_specificity]
    pool = eligible or results
    champion = max(pool, key=lambda r: (r.metrics.sensitivity, r.metrics.auroc))
    console.print(
        f"[bold green]Slice champion: {champion.name}  (aggregator={champion.aggregator})[/]"
    )

    # Persist artifacts (separate file paths from the patient-level run).
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    PROC_DIR.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(
        [{"model": r.name, "aggregator": r.aggregator, **r.metrics.as_row(),
          "sens_ci_lo": r.sens_ci[1], "sens_ci_hi": r.sens_ci[2],
          "auroc_ci_lo": r.auroc_ci[1], "auroc_ci_hi": r.auroc_ci[2]}
         for r in results]
    ).sort_values("sensitivity", ascending=False).to_csv(
        REPORTS_DIR / "model_selection_slice.csv", index=False
    )
    pd.DataFrame(
        [{"model": r.name, "aggregator": r.aggregator,
          "patient_sk": pg, "y_true": yt, "y_prob": yp}
         for r in results
         for pg, yt, yp in zip(r.oof_patient_groups, r.oof_patient_true,
                                r.oof_patient_proba)]
    ).to_parquet(PROC_DIR / "model_oof_slice_patient.parquet", index=False)

    (REPORTS_DIR / "champion_slice.json").write_text(
        json.dumps({
            "name": champion.name,
            "aggregator": champion.aggregator,
            "threshold": champion.threshold,
            "k": args.k,
            "calibrate": bool(args.calibrate),
            "oof_sensitivity": champion.metrics.sensitivity,
            "oof_specificity": champion.metrics.specificity,
            "oof_auroc": champion.metrics.auroc,
        }, indent=2),
        encoding="utf-8",
    )
    console.print(f"[bold green]Done in {time.time()-t0:.1f}s[/]")


def cmd_evaluate_slice(args: argparse.Namespace) -> None:
    """Refit slice-level champion on full train, evaluate once on test."""
    t0 = time.time()
    champ_path = REPORTS_DIR / "champion_slice.json"
    if not champ_path.exists():
        raise SystemExit("Run `train-slice` first; champion_slice.json missing.")
    info = json.loads(champ_path.read_text(encoding="utf-8"))
    name, aggregator = info["name"], info["aggregator"]
    threshold = float(info["threshold"])
    k = info.get("k") or 15
    calibrate = bool(info.get("calibrate", False))

    console.print(f"[cyan]==> Refitting slice champion `{name}` (agg={aggregator}, k={k}, calibrate={calibrate})[/]")
    split = make_slice_split()

    # If calibration was used in CV, we must refit Isotonic on the
    # train OOF patient-level predictions and apply it to test.
    iso = None
    if calibrate:
        from sklearn.isotonic import IsotonicRegression
        from acv.modeling.slice_cv import _slice_oof, _patient_truth

        console.print("[cyan]==> Computing train OOF for isotonic calibration[/]")
        oof_slice_train = _slice_oof(
            PIPELINES[name], split.X_train, split.y_train,
            split.groups_train, n_splits=5,
            seed=settings.random_seed, k=k,
        )
        oof_pat_train, _ = aggregate_to_patient(
            oof_slice_train, split.groups_train,
            split.slice_weights_train, aggregator=aggregator,
        )
        pat_truth_train, _ = _patient_truth(split.y_train, split.groups_train)
        iso = IsotonicRegression(out_of_bounds="clip")
        iso.fit(oof_pat_train, pat_truth_train)

    # Now train the final pipeline on FULL train and predict on test.
    pipe = PIPELINES[name](k=k, seed=settings.random_seed)
    pipe.fit(split.X_train, split.y_train)

    if hasattr(pipe.named_steps["est"], "predict_proba"):
        slice_proba = pipe.predict_proba(split.X_test)[:, 1]
    else:
        slice_proba = pipe.predict(split.X_test).astype(float)

    pat_proba, pat_groups = aggregate_to_patient(
        slice_proba, split.groups_test, split.slice_weights_test, aggregator=aggregator
    )
    if iso is not None:
        pat_proba = iso.transform(pat_proba)
    pat_truth_df = pd.DataFrame({"g": split.groups_test, "y": split.y_test}).groupby("g", sort=True)["y"].max()
    pat_truth = pat_truth_df.to_numpy()

    metrics = compute_metrics(pat_truth, pat_proba, threshold)
    sens_at_thr = lambda yt, yp: sensitivity(yt, (yp >= threshold).astype(int))
    sens_pt, sens_lo, sens_hi = bootstrap_metric(
        pat_truth, pat_proba, sens_at_thr, n_resamples=args.bootstrap,
        groups=pat_groups, random_state=settings.random_seed,
    )
    from sklearn.metrics import roc_auc_score
    try:
        _, auroc_lo, auroc_hi = bootstrap_metric(
            pat_truth, pat_proba, roc_auc_score, n_resamples=args.bootstrap,
            groups=pat_groups, random_state=settings.random_seed,
        )
    except ValueError:
        auroc_lo, auroc_hi = float("nan"), float("nan")

    console.print(f"[bold]Slice-level test metrics (n={pat_truth.size} patients):[/]")
    console.print(f"  aggregator  = {aggregator}")
    console.print(f"  threshold   = {threshold:.3f}")
    console.print(f"  sensitivity = {metrics.sensitivity:.3f}  95% CI [{sens_lo:.2f}, {sens_hi:.2f}]")
    console.print(f"  specificity = {metrics.specificity:.3f}")
    console.print(f"  AUROC       = {metrics.auroc:.3f}  95% CI [{auroc_lo:.2f}, {auroc_hi:.2f}]")
    console.print(f"  AUPRC       = {metrics.auprc:.3f}")
    console.print(f"  confusion   = {metrics.confusion}")

    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    with (MODELS_DIR / "champion_slice.pkl").open("wb") as f:
        pickle.dump(
            {
                "name": name, "aggregator": aggregator, "threshold": threshold,
                "pipeline": pipe, "feature_names": split.feature_names,
                "calibrator": iso, "k": k,
            },
            f,
        )
    console.print(f"   wrote {MODELS_DIR / 'champion_slice.pkl'}")
    console.print(f"[bold green]Done in {time.time()-t0:.1f}s[/]")


