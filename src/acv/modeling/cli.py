def cmd_train(args: argparse.Namespace) -> None:
    t0 = time.time()
    console.print("[cyan]==> Loading features[/]")
    split = make_split()
    console.print(f"   train: {split.n_train_patients} patients | "
                  f"test: {split.n_test_patients} patients | "
                  f"features: {len(split.feature_names)}")

    results: list[CVResult] = []
    for name, factory in PIPELINES.items():
        console.print(f"[cyan]==> CV {name}[/]")
        # clinical baseline uses the clinical-only split
        if name == "baseline_clinical_logreg":
            sub = make_split(clinical_only=True)
            r = run_cv(
                name, factory,
                sub.X_train, sub.y_train, sub.groups_train,
                seed=settings.random_seed, bootstrap_n=args.bootstrap,
                k=len(sub.feature_names),
            )
        elif name == "baseline_majority":
            r = run_cv(
                name, factory,
                split.X_train, split.y_train, split.groups_train,
                seed=settings.random_seed, bootstrap_n=args.bootstrap,
                k=None,
            )
        else:
            r = run_cv(
                name, factory,
                split.X_train, split.y_train, split.groups_train,
                seed=settings.random_seed, bootstrap_n=args.bootstrap,
                k=args.k,
            )
        results.append(r)
        m = r.metrics
        console.print(
            f"   sens={m.sensitivity:.3f} [{r.sens_ci[1]:.2f},{r.sens_ci[2]:.2f}]  "
            f"spec={m.specificity:.3f}  auroc={m.auroc:.3f}  thr={r.threshold:.3f}"
        )

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    PROC_DIR.mkdir(parents=True, exist_ok=True)
    _save_selection_csv(results, REPORTS_DIR / "model_selection.csv")
    _save_oof(results, PROC_DIR / "model_oof_predictions.parquet")

    champion = _pick_champion(results)
    console.print(_pretty_table(results))
    console.print(f"[bold green]Champion: {champion.name}[/]")

    # Save champion choice as JSON for the evaluate step.
    (REPORTS_DIR / "champion.json").write_text(
        json.dumps(
            {"name": champion.name, "threshold": champion.threshold,
             "k": args.k}, indent=2
        ),
        encoding="utf-8",
    )

    _write_model_card(results, champion, test_metrics=None,
                      path=REPORTS_DIR / "model_card.md")
    console.print(f"[bold green]Done in {time.time()-t0:.1f}s[/]")


