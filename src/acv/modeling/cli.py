def cmd_evaluate(args: argparse.Namespace) -> None:
    """One-shot test-set evaluation of the champion. Writes models/champion.pkl."""
    t0 = time.time()
    champ_path = REPORTS_DIR / "champion.json"
    if not champ_path.exists():
        raise SystemExit("Run `train` first; champion.json missing.")
    champ_info = json.loads(champ_path.read_text(encoding="utf-8"))
    name = champ_info["name"]
    threshold = float(champ_info["threshold"])
    k = champ_info.get("k") or 15

    console.print(f"[cyan]==> Refitting champion `{name}` on full train[/]")
    if name == "baseline_clinical_logreg":
        split = make_split(clinical_only=True)
        factory = PIPELINES[name]
        pipe = factory(k=len(split.feature_names), seed=settings.random_seed)
    elif name == "baseline_majority":
        split = make_split()
        pipe = PIPELINES[name](seed=settings.random_seed)
    else:
        split = make_split()
        pipe = PIPELINES[name](k=k, seed=settings.random_seed)
    pipe.fit(split.X_train, split.y_train)

    if hasattr(pipe.named_steps["est"], "predict_proba"):
        proba = pipe.predict_proba(split.X_test)[:, 1]
    else:
        proba = pipe.predict(split.X_test).astype(float)

    metrics = compute_metrics(split.y_test, proba, threshold)
    sens_at_thr = lambda yt, yp: sensitivity(yt, (yp >= threshold).astype(int))
    sens_pt, sens_lo, sens_hi = bootstrap_metric(
        split.y_test, proba, sens_at_thr,
        n_resamples=args.bootstrap, groups=split.groups_test,
        random_state=settings.random_seed,
    )
    from sklearn.metrics import roc_auc_score
    try:
        auroc_pt, auroc_lo, auroc_hi = bootstrap_metric(
            split.y_test, proba, roc_auc_score,
            n_resamples=args.bootstrap, groups=split.groups_test,
            random_state=settings.random_seed,
        )
    except ValueError:
        auroc_pt, auroc_lo, auroc_hi = metrics.auroc, float("nan"), float("nan")

    console.print(f"[bold]Test set metrics ({split.n_test_patients} patients):[/]")
    console.print(f"  threshold   = {threshold:.3f}")
    console.print(f"  sensitivity = {metrics.sensitivity:.3f}  95% CI [{sens_lo:.2f}, {sens_hi:.2f}]")
    console.print(f"  specificity = {metrics.specificity:.3f}")
    console.print(f"  AUROC       = {metrics.auroc:.3f}  95% CI [{auroc_lo:.2f}, {auroc_hi:.2f}]")
    console.print(f"  AUPRC       = {metrics.auprc:.3f}")
    console.print(f"  confusion   = {metrics.confusion}")

    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    with (MODELS_DIR / "champion.pkl").open("wb") as f:
        pickle.dump(
            {
                "name": name,
                "threshold": threshold,
                "pipeline": pipe,
                "feature_names": split.feature_names,
            },
            f,
        )
    console.print(f"   wrote {MODELS_DIR / 'champion.pkl'}")

    test_dict = {
        "sensitivity": {"point": metrics.sensitivity, "low": sens_lo, "high": sens_hi},
        "specificity": {"point": metrics.specificity, "low": float('nan'), "high": float('nan')},
        "auroc": {"point": metrics.auroc, "low": auroc_lo, "high": auroc_hi},
        "auprc": metrics.auprc,
        "brier": metrics.brier,
        "tp/fp/tn/fn": f"{metrics.confusion['tp']}/{metrics.confusion['fp']}/{metrics.confusion['tn']}/{metrics.confusion['fn']}",
    }
    # rewrite model card so it includes the test block.
    csv_path = REPORTS_DIR / "model_selection.csv"
    sel_df = pd.read_csv(csv_path)
    # rebuild a fake CVResult list for the table (we only need the metrics);
    # easier: rewrite from the persisted CSV.
    md_lines = (REPORTS_DIR / "model_card.md").read_text(encoding="utf-8").splitlines()
    held_out_marker = "## Held-out test set"
    if held_out_marker in (REPORTS_DIR / "model_card.md").read_text(encoding="utf-8"):
        # already contains a test block; replace it via rewrite from scratch
        pass
    # simpler: append test section at end.
    new_block = [
        "",
        f"## Held-out test set (refitted champion = `{name}`)",
        "",
        "| metric | value | 95% CI |",
        "|---|---|---|",
        f"| sensitivity | {metrics.sensitivity:.3f} | [{sens_lo:.2f}, {sens_hi:.2f}] |",
        f"| specificity | {metrics.specificity:.3f} | — |",
        f"| AUROC       | {metrics.auroc:.3f} | [{auroc_lo:.2f}, {auroc_hi:.2f}] |",
        f"| AUPRC       | {metrics.auprc:.3f} | — |",
        f"| Brier       | {metrics.brier:.3f} | — |",
        f"| TP/FP/TN/FN | {metrics.confusion['tp']}/{metrics.confusion['fp']}/{metrics.confusion['tn']}/{metrics.confusion['fn']} | — |",
    ]
    # write a clean rewrite
    md = (REPORTS_DIR / "model_card.md").read_text(encoding="utf-8")
    if held_out_marker not in md:
        md += "\n" + "\n".join(new_block) + "\n"
    else:
        # truncate previous test block and add fresh
        idx = md.find(held_out_marker)
        # find next "## " or EOF
        rest = md[idx:]
        next_section = rest.find("\n## ", 1)
        if next_section == -1:
            md = md[:idx] + "\n".join(new_block) + "\n"
        else:
            md = md[:idx] + "\n".join(new_block) + rest[next_section:]
    (REPORTS_DIR / "model_card.md").write_text(md, encoding="utf-8")
    console.print(f"[bold green]Done in {time.time()-t0:.1f}s[/]")


