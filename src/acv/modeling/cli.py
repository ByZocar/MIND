def _parse() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="ACV window classifier modeling pipeline.")
    sub = p.add_subparsers(dest="cmd", required=True)

    p_train = sub.add_parser("train", help="Run CV across all pipelines.")
    p_train.add_argument("--k", type=int, default=15, help="Top-K features by MI.")
    p_train.add_argument("--bootstrap", type=int, default=1000, help="Bootstrap resamples.")

    p_eval = sub.add_parser("evaluate", help="Refit champion and evaluate on test.")
    p_eval.add_argument("--bootstrap", type=int, default=1000, help="Bootstrap resamples.")

    p_ts = sub.add_parser("train-slice", help="Slice-level CV (MIL) across pipelines + aggregators.")
    p_ts.add_argument("--k", type=int, default=20, help="Top-K features by MI inside each fold.")
    p_ts.add_argument("--bootstrap", type=int, default=500, help="Bootstrap resamples.")
    p_ts.add_argument("--aggregators", type=str, default="",
                      help="Comma-separated aggregators (default: all).")
    p_ts.add_argument("--calibrate", action="store_true",
                      help="Isotonic-calibrate patient-level OOF probabilities.")

    p_es = sub.add_parser("evaluate-slice", help="Refit slice champion + 1-shot test eval.")
    p_es.add_argument("--bootstrap", type=int, default=1000, help="Bootstrap resamples.")

    return p.parse_args()


